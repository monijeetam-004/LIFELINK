"""Prepare the inputs of frontend/scripts/qa-crawl.mjs for the QA stack.

    python crawl_params.py INVENTORY_JSON OUT_DIR [--api http://localhost:8000]

* OUT_DIR/fe_routes.json -- every route of frontend/src/App.tsx with its
  guard and roles (from the inventory generated by scripts/qa_inventory.py).
* OUT_DIR/params.json    -- real ids for the parameterised routes, created
  through the public API with the demo accounts (no database edits):
  a donation by the demo donor, verified by the demo admin, and its
  certificate (cert_id, verify_code); the demo patient's blood request
  (request_id); and the demo family member's linked patient (patient_id).
"""

from __future__ import annotations

import argparse
import json
from datetime import date
from pathlib import Path

import httpx

ORIGIN = {"Origin": "http://localhost:5173"}
PW = "LifeLink-Demo-2026!"  # documented, non-secret demo seed password


def client(api: str, role: str) -> httpx.Client:
    c = httpx.Client(base_url=api, headers=ORIGIN, timeout=30)
    r = c.post(
        "/auth/login", json={"email": f"demo.{role}@lifelink-demo.example.com", "password": PW}
    )
    r.raise_for_status()
    return c


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("inventory")
    ap.add_argument("out")
    ap.add_argument("--api", default="http://localhost:8000")
    a = ap.parse_args()
    out = Path(a.out)
    out.mkdir(parents=True, exist_ok=True)
    inv = json.loads(Path(a.inventory).read_text())
    routes = [
        {"path": r["path"], "auth": r["guarded"], "roles": r["roles"]}
        for r in inv["frontend_routes"]
    ]
    (out / "fe_routes.json").write_text(json.dumps(routes, indent=1))

    donor, admin = client(a.api, "donor"), client(a.api, "admin")
    patient, family = client(a.api, "patient"), client(a.api, "family")
    d = donor.post(
        "/donors/me/donations",
        json={"donated_on": date.today().isoformat(), "units": 1, "hospital_name": "QA Crawl"},
    )
    d.raise_for_status()
    admin.post(f"/donations/{d.json()['id']}/verify", json={}).raise_for_status()
    cert = donor.post("/certificates", json={"donation_id": d.json()["id"]})
    cert.raise_for_status()
    c = cert.json()
    reqs = patient.get("/blood-requests")
    reqs.raise_for_status()
    body = reqs.json()
    items = body["items"] if isinstance(body, dict) and "items" in body else body
    links = family.get("/family/links")
    links.raise_for_status()
    lb = links.json()
    first_link = (lb["items"] if isinstance(lb, dict) else lb)[0]
    params = {
        "cert_id": c["id"],
        "verify_code": c["verify_code"],
        "request_id": items[0]["id"],
        "patient_id": first_link["patient_user_id"],
    }
    missing = [k for k, v in params.items() if not v]
    if missing:
        raise SystemExit(f"could not resolve: {missing}; inputs incomplete")
    (out / "params.json").write_text(json.dumps(params, indent=1))
    print(json.dumps({k: "<id>" for k in params}))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
