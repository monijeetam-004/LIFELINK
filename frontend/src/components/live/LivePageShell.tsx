import type { ReactNode } from "react";
import { Link } from "react-router-dom";

import { useAuth } from "../../lib/auth";
import type { Role } from "../../lib/types";

/**
 * Shared frame for the research / explanation pages. They used to be static
 * mock-ups; now every number on them comes from a real endpoint. The frame
 * states that plainly, discloses that development data is synthetic, and
 * asks visitors to sign in with a role that may call those endpoints.
 */
export default function LivePageShell({
  title,
  intro,
  roles,
  children,
}: {
  title: string;
  intro: ReactNode;
  roles: Role[];
  children: ReactNode;
}) {
  const { user } = useAuth();
  const allowed = !!user && roles.includes(user.role);
  return (
    <div className="min-h-screen bg-surface">
      <header className="border-b border-border-subtle bg-surface-container-lowest">
        <div className="max-w-container-max mx-auto px-4 sm:px-6 lg:px-10 py-4 flex items-center justify-between gap-4">
          <Link to="/" className="flex items-center gap-2 min-w-0">
            <img alt="" aria-hidden="true" className="h-8 w-8" src="/brand/lifelink-logo.svg" />
            <span className="font-headline-sm text-headline-sm text-primary font-bold">LifeLink</span>
          </Link>
          {user ? (
            <span className="text-body-sm text-on-surface-variant truncate">
              Signed in as {user.full_name} ({user.role.toLowerCase()})
            </span>
          ) : (
            <Link to="/login" className="text-primary font-label-md underline">Sign in</Link>
          )}
        </div>
      </header>
      <main className="max-w-container-max mx-auto px-4 sm:px-6 lg:px-10 py-6 flex flex-col gap-6">
        <div>
          <h1 className="font-headline-lg text-headline-lg text-on-surface">{title}</h1>
          <div className="mt-2 text-body-md text-on-surface-variant max-w-3xl">{intro}</div>
        </div>
        <p
          role="note"
          className="rounded-lg border border-amber-300 bg-amber-50 text-amber-900 px-4 py-3 text-body-sm"
        >
          Live computation on this deployment's own data. In development and in the research
          evaluation that data is <strong>synthetic</strong> (generated by the seed and simulation
          scripts) — results describe the algorithm's behaviour, not real patients, hospitals or
          clinical outcomes.
        </p>
        {allowed ? (
          children
        ) : (
          <section
            aria-labelledby="signin-needed"
            className="rounded-xl border border-border-subtle bg-surface-container-low p-6"
          >
            <h2 id="signin-needed" className="font-headline-sm text-headline-sm">
              Sign in to run this page
            </h2>
            <p className="mt-2 text-body-md text-on-surface-variant">
              This page calls the live engine, which is available to these roles:{" "}
              {roles.map((r) => r.toLowerCase()).join(", ")}.
            </p>
            <Link
              to="/login"
              className="inline-block mt-4 bg-primary text-on-primary px-4 py-2 rounded-lg font-label-md"
            >
              Sign in
            </Link>
          </section>
        )}
      </main>
    </div>
  );
}
